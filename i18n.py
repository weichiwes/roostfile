_language = "en"


def set_language(code):
    global _language
    _language = code if code in LANGUAGES else "en"


def language():
    return _language


def app_name():
    return APP_NAME[_language]


def t(text, **values):
    wording = ZH.get(text, text) if _language == "zh" else text
    return wording.format(**values) if values else wording


def condition_label(label):
    """Show a parsed condition such as ``Last 14 days`` in the current language."""
    match = re.fullmatch(r"Last (\d+) days", str(label))
    if match and _language == "zh":
        return f"最近 {match[1]} 天"
    return t(label)
